// A private SDK build artifact, not a renderer or public contract generator.
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";

const root = path.resolve(import.meta.dirname, "../../..");
const sdk = path.join(root, "packages/sdk-ts");
const artifact = path.join(sdk, "src/preview-digest.generated.ts");
const provenance = path.join(sdk, "preview-digest/provenance.json");
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const inputs = ["rust-toolchain.toml", ...[
  "preview-digest/Cargo.toml", "preview-digest/Cargo.lock", "preview-digest/src/lib.rs",
  "scripts/generate-preview-digest.mjs", "LICENSE",
].map(name => `packages/sdk-ts/${name}`)];
const sources = Object.fromEntries(inputs.map(name => [name, hash(fs.readFileSync(path.join(root, name)))]));
const flags = ["-C", "target-feature=+simd128", "-C", "link-arg=-zstack-size=65536", "-C", "link-arg=--max-memory=262144",
  "--remap-path-prefix=<repository>=opencut", "--remap-path-prefix=<cargo-home>=cargo"];
const artifactOnly = process.argv.includes("--artifact-only");
const check = artifactOnly || process.argv.includes("--check");
let bytes;
if (artifactOnly) {
  const source = fs.readFileSync(artifact, "utf8");
  bytes = Buffer.from([...source.matchAll(/^  "([A-Za-z0-9+/=]+)"/gm)].map(match => match[1]).join(""), "base64");
} else {
  const pinned = fs.readFileSync(path.join(root, "rust-toolchain.toml"), "utf8").match(/channel = "([^"]+)"/)[1];
  const compiler = execFileSync("rustc", ["--version"], { cwd: root, encoding: "utf8" });
  if (!compiler.startsWith(`rustc ${pinned} `)) throw Error("Digest requires the repository's pinned Rust compiler");
  const cargoHome = path.resolve(process.env.CARGO_HOME ?? path.join(os.homedir(), ".cargo"));
  const encodedFlags = flags.map(flag => flag.replace("<repository>", root).replace("<cargo-home>", cargoHome)).join("\x1f");
  execFileSync("cargo", ["build", "--manifest-path", path.join(sdk, "preview-digest/Cargo.toml"),
    "--target", "wasm32-unknown-unknown", "--target-dir", path.join(root, "target/browser-digest"),
    "--release", "--locked", "--offline"], { cwd: root, env: { ...process.env, CARGO_ENCODED_RUSTFLAGS: encodedFlags }, stdio: "inherit" });
  bytes = fs.readFileSync(path.join(root, "target/browser-digest/wasm32-unknown-unknown/release/opencut_preview_digest.wasm"));
}
const module = new WebAssembly.Module(bytes);
if (WebAssembly.Module.imports(module).length) throw Error("Digest must not import host capabilities");
const instance = new WebAssembly.Instance(module, {});
if (instance.exports.memory.buffer.byteLength > 262144) throw Error("Digest exceeds bounded memory");
const record = { algorithm: "BLAKE3-256", dependency: "blake3=1.8.7", target: "wasm32-unknown-unknown",
  rustflags: flags, source_files: sources, wasm_sha256: hash(bytes), wasm_bytes: bytes.length,
  initial_memory_bytes: instance.exports.memory.buffer.byteLength, maximum_memory_bytes: 262144 };
const generated = "// Generated by scripts/generate-preview-digest.mjs; do not hand edit.\n" +
  `// Complete source, locked dependencies and SHA-256: preview-digest/provenance.json.\n` +
  "export const previewDigestWasm =\n" + bytes.toString("base64").match(/.{1,100}/g).map((line, index, all) =>
    `  "${line}"${index + 1 === all.length ? ";" : " +"}`).join("\n") + "\n";
if (check) {
  if (fs.readFileSync(artifact, "utf8") !== generated || fs.readFileSync(provenance, "utf8") !== JSON.stringify(record, null, 2) + "\n")
    throw Error("Preview digest artifact or source provenance is stale; run npm run digest:generate");
} else {
  fs.writeFileSync(artifact, generated);
  fs.writeFileSync(provenance, JSON.stringify(record, null, 2) + "\n");
}
console.log(JSON.stringify({ checked: check, rebuilt: !artifactOnly, wasm_sha256: record.wasm_sha256, wasm_bytes: bytes.length }));
